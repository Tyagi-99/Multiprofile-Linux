#!/usr/bin/env bash
# Rootless per-user install. No sudo, no package manager, nothing outside $HOME.
#
# This exists because the only packaged path is a .deb, and the machines this
# runs on include Arch. Rather than invent a second packaging format, this
# installs what INSTALLATION.md already describes as the from-source path --
# a venv plus the console -- and adds the three things that turn it into
# something usable daily: a stable launch command on PATH, a desktop entry,
# and icons.
#
# It is idempotent: running it again upgrades in place and never touches
# ~/.local/share/multiprofile, which is where the profiles live.
set -euo pipefail

SOURCE_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
PREFIX=${PREFIX:-$HOME/.local}
APP_DIR=${APP_DIR:-$PREFIX/lib/multiprofile}
VENV="$APP_DIR/venv"
BIN="$PREFIX/bin/multiprofile"
DESKTOP_DIR="$PREFIX/share/applications"
ICON_ROOT="$PREFIX/share/icons/hicolor"

say() { printf '\n== %s\n' "$*"; }

say "source:  $SOURCE_DIR"
say "install: $APP_DIR"

# The data directory is deliberately NOT touched here. An upgrade that
# rewrote the operator's profiles would be the worst possible bug in an
# installer, so this script has no code that writes to it at all.
DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/multiprofile"
if [ -e "$DATA_DIR" ]; then
  say "existing data at $DATA_DIR will be left exactly as it is"
fi

PY=${PYTHON:-python3}
"$PY" - <<'PYEOF'
import sys
if sys.version_info < (3, 11):
    sys.exit(f"need Python 3.11+, this is {sys.version.split()[0]}")
PYEOF

say "creating the virtual environment"
mkdir -p "$APP_DIR"
# --system-site-packages, deliberately.
#
# The desktop window is pywebview on GTK, and pywebview needs PyGObject plus
# the WebKit2GTK typelibs. Those cannot be pip-installed in any reliable way:
# they are distro packages (python-gobject / python3-gi, webkit2gtk). An
# isolated venv therefore cannot see them, pywebview's GTK import fails, and
# `open_ui` silently falls back to `webbrowser.open` -- so `multiprofile`
# opens a TAB IN THE OPERATOR'S OWN BROWSER instead of its own window.
#
# That is not a cosmetic difference for this product. The console ends up in
# the operator's personal browsing session, beside their own tabs, which is
# the one place a profile manager should not be.
#
# Measured on this machine before the flag was added:
#   system python   gi + Gtk 3.0 + WebKit2 4.1   OK
#   venv python     ModuleNotFoundError: No module named 'gi'
#   log             [pywebview] GTK cannot be loaded -> system browser
#
# Project dependencies still install into the venv and still take precedence
# over anything with the same name outside it.
if [ -x "$VENV/bin/python" ] && \
   ! grep -q 'include-system-site-packages = true' "$VENV/pyvenv.cfg" 2>/dev/null; then
  say "rebuilding the virtual environment so the GTK bindings are visible"
  rm -rf "$VENV"
fi
if [ ! -x "$VENV/bin/python" ]; then
  "$PY" -m venv --system-site-packages "$VENV"
fi
"$VENV/bin/python" -m pip install --quiet --upgrade pip
# Not editable: an installed copy must not break because the checkout moved.
"$VENV/bin/python" -m pip install --quiet "$SOURCE_DIR[all]"

say "installing the launch command"
mkdir -p "$PREFIX/bin"
cat > "$BIN" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install-local.sh -- do not edit, it is overwritten.
exec "$VENV/bin/multiprofile" "\$@"
EOF
chmod 0755 "$BIN"

say "installing the desktop entry"
mkdir -p "$DESKTOP_DIR"
# Exec is the absolute path: a desktop launcher does not necessarily inherit
# the PATH a login shell has, which is the usual reason a .desktop file works
# from a terminal and does nothing from the application menu.
sed -e "s|^Exec=multiprofile$|Exec=$BIN|" \
    "$SOURCE_DIR/packaging/debian/multiprofile.desktop" \
    > "$DESKTOP_DIR/multiprofile.desktop"
chmod 0644 "$DESKTOP_DIR/multiprofile.desktop"

say "installing the backup command and its timer"
mkdir -p "$PREFIX/bin"
cat > "$PREFIX/bin/multiprofile-backup" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install-local.sh -- do not edit, it is overwritten.
exec "$SOURCE_DIR/scripts/backup.sh" "\$@"
EOF
chmod 0755 "$PREFIX/bin/multiprofile-backup"

# The timer is installed but NOT enabled. Enabling something that writes
# hundreds of megabytes on a schedule is the operator's decision, not an
# installer's -- so it is put within reach and the command to start it is
# printed, which is as far as this should go on its own.
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
if [ -d "$SOURCE_DIR/packaging/systemd" ]; then
  mkdir -p "$UNIT_DIR"
  cp "$SOURCE_DIR/packaging/systemd/multiprofile-backup.service" "$UNIT_DIR/"
  cp "$SOURCE_DIR/packaging/systemd/multiprofile-backup.timer"   "$UNIT_DIR/"
  if command -v systemctl >/dev/null 2>&1; then
    systemctl --user daemon-reload 2>/dev/null || true
  fi
fi

say "installing icons"
for png in "$SOURCE_DIR"/packaging/icons/hicolor/*/apps/multiprofile.png; do
  [ -e "$png" ] || continue
  size=$(basename "$(dirname "$(dirname "$png")")")
  mkdir -p "$ICON_ROOT/$size/apps"
  cp "$png" "$ICON_ROOT/$size/apps/multiprofile.png"
done
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
  gtk-update-icon-cache -q -t -f "$ICON_ROOT" 2>/dev/null || true
fi
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database -q "$DESKTOP_DIR" 2>/dev/null || true
fi

say "verifying"
INSTALLED=$("$BIN" --version)
echo "  $INSTALLED"
case ":$PATH:" in
  *":$PREFIX/bin:"*) echo "  $PREFIX/bin is on PATH" ;;
  *) echo "  WARNING: $PREFIX/bin is NOT on PATH. Add it to your shell profile:"
     echo "           export PATH=\"$PREFIX/bin:\$PATH\"" ;;
esac
if "$BIN" --doctor; then
  echo "  doctor: ok"
else
  echo "  doctor reported something to fix (above). The install itself is fine."
fi
# Stated, not assumed: without GTK the desktop window silently becomes a tab
# in whatever browser the system opens, and the operator should know which
# they have before they rely on it.
if "$VENV/bin/python" - <<'PYCHECK' 2>/dev/null
import gi
gi.require_version("Gtk", "3.0")
from gi.repository import Gtk  # noqa: F401
import webview  # noqa: F401
PYCHECK
then
  echo "  desktop window: GTK available, 'multiprofile' opens its own window"
else
  echo "  desktop window: GTK bindings NOT available -- 'multiprofile' will open"
  echo "                  a tab in your system browser instead. Install them with:"
  echo "                    Arch:          sudo pacman -S python-gobject webkit2gtk"
  echo "                    Debian/Ubuntu: sudo apt install python3-gi gir1.2-webkit2-4.1"
  echo "                  then re-run this script."
fi

BACKUP_STATE="not enabled"
if command -v systemctl >/dev/null 2>&1 \
   && systemctl --user is-enabled multiprofile-backup.timer >/dev/null 2>&1; then
  BACKUP_STATE="enabled ($(systemctl --user list-timers multiprofile-backup.timer \
    --no-legend 2>/dev/null | awk '{print $1, $2}' | head -1))"
fi

cat <<EOF

Installed.

  multiprofile                 the desktop window
  multiprofile --server-only   API + console on http://127.0.0.1:8765/
  multiprofile --version       what is installed here
  multiprofile --doctor        diagnose this installation
  multiprofile-backup          a verified backup, now

Automatic daily backups: $BACKUP_STATE
  systemctl --user enable --now multiprofile-backup.timer

Your data stays in $DATA_DIR and was not touched.
Uninstall with scripts/uninstall-local.sh -- it removes this install and
leaves your profiles alone.
EOF
